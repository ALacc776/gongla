// Builds a migration that upserts the built-in scenarios from scenarios/*.json.
// Usage: node scripts/build-scenario-seed.mjs > supabase/migrations/<timestamp>_seed_scenarios.sql
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = new URL('../scenarios/', import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
const quote = (s) => `'${s.replaceAll("'", "''")}'`;

const rows = files.map((file) => {
  const { id, pack, spec } = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  return `  (${quote(id)}, null, ${quote(pack)}, ${quote(JSON.stringify(spec))}::jsonb, false)`;
});

console.log(`-- Generated by scripts/build-scenario-seed.mjs from scenarios/*.json. Do not edit by hand.
insert into scenarios (id, owner_id, pack, spec, is_custom)
values
${rows.join(',\n')}
on conflict (id) do update set pack = excluded.pack, spec = excluded.spec;`);
